-- Turn on foreign-key checking (off by default)
pragma foreign_keys=on;

-- Clear out anything that was there before
drop table if exists Ticket;
drop table if exists Passenger;
drop table if exists Flight;
drop table if exists Aircraft;
drop table if exists ACModel;
drop table if exists Airport;

----------------- Data definition -------------------------

CREATE TABLE if not exists Airport (
  AirportCode char(3) primary key,
  AirportName varchar(50) unique not null,
  AirportAddress varchar(50) not null,
  Latitude float(6) not null,
  Longitude float(6) not null,
  elevation integer not null
);

create table if not exists ACModel (
  ACModelID integer primary key autoincrement,
  ModelName varchar(15),
  Manufacturer varchar(30) not null,
  Seats integer,
  FuelCapy integer, -- in pounds, at sea level and 25 degrees C
  MTOW integer -- maximum takeoff weight in pounds, at sea level and 25 degrees C
);

create table if not exists Aircraft (
  ACID integer primary key autoincrement,
  ACModelID integer references ACModel not null,
  RegNum char(8) unique
);

CREATE TABLE if not exists Flight (
  FltNum integer primary key, -- pretend this never changes.  In fact, it does, but rarely.  
  Origin char(3) references Airport not null,
  Dest char(3) references Airport not null,
  Departs time,
  Arrives time,
  ACModelID integer references ACModel
);

CREATE TABLE if not exists Passenger (
  PsgrID integer primary key autoincrement,
  FirstName varchar(20) not null,
  LastName varchar(30) not null,
  PsgrAddress varchar(50),
  Phone char(10),
  Birthdate date,
unique (FirstName, LastName) -- not realistic, but it makes debugging a lot easier
);

create table if not exists Ticket (
  TktNum integer primary key autoincrement,
  PsgrID integer references Passenger not null,
  FltNum integer references Flight not null,
  FltDate date not null,
  Seat char(3),
unique(PsgrId, FltNum, FltDate),
unique(FltNum, FltDate, Seat)
);

